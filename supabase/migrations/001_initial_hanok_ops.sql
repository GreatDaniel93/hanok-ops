create table public.ops_stores (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint ops_stores_code_format check (code ~ '^[A-Z0-9]{2,8}$')
);

create table public.ops_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text not null default 'User',
  role text not null default 'pending' check (role in ('admin','hq','store','pending')),
  store_id uuid references public.ops_stores(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ops_profiles_store_role_check check (role <> 'store' or store_id is not null)
);

create or replace function ops_private.current_role()
returns text language sql stable security definer set search_path=''
as $$ select p.role from public.ops_profiles p where p.user_id=(select auth.uid()) limit 1 $$;

create or replace function ops_private.current_store_id()
returns uuid language sql stable security definer set search_path=''
as $$ select p.store_id from public.ops_profiles p where p.user_id=(select auth.uid()) limit 1 $$;

revoke all on function ops_private.current_role() from public,anon;
revoke all on function ops_private.current_store_id() from public,anon;
grant execute on function ops_private.current_role() to authenticated;
grant execute on function ops_private.current_store_id() to authenticated;

create table public.ops_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_no bigint generated by default as identity unique,
  store_id uuid not null references public.ops_stores(id) on delete restrict,
  created_by uuid not null references public.ops_profiles(user_id) on delete restrict,
  assigned_to uuid references public.ops_profiles(user_id) on delete set null,
  title text not null,
  description text not null default '',
  reported_by text,
  category text not null default 'Other' check (category in (
    'Maintenance','Supplier / Stock','IT / POS','Marketing','HR / Staff',
    'Finance','Landlord / Centre','Health & Safety','Other'
  )),
  priority text not null default 'normal' check (priority in ('normal','urgent')),
  status text not null default 'new' check (status in ('new','accepted','in_progress','waiting','completed')),
  due_at timestamptz,
  follow_up_at timestamptz,
  waiting_reason text,
  resolution text,
  accepted_at timestamptz,
  completed_at timestamptz,
  completed_by uuid references public.ops_profiles(user_id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ops_tickets_reported_by_length check (reported_by is null or char_length(trim(reported_by)) between 1 and 100),
  constraint ops_tickets_waiting_requires_followup check (
    status <> 'waiting' or (follow_up_at is not null and waiting_reason is not null and length(trim(waiting_reason)) > 0)
  ),
  constraint ops_tickets_completed_requires_resolution check (
    status <> 'completed' or (resolution is not null and length(trim(resolution)) > 0)
  )
);

