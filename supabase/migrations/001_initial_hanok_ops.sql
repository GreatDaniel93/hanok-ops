create or replace function ops_private.touch_updated_at()
returns trigger language plpgsql security invoker set search_path=''
as $$ begin new.updated_at:=now(); return new; end $$;

create or replace function ops_private.normalize_ticket_state()
returns trigger language plpgsql security invoker set search_path=''
as $$
begin
  new.updated_at:=now();
  if new.status='accepted' and old.status is distinct from 'accepted' then new.accepted_at:=coalesce(new.accepted_at,now()); end if;
  if new.status='completed' and old.status is distinct from 'completed' then
    new.completed_at:=coalesce(new.completed_at,now());
    new.completed_by:=coalesce(new.completed_by,(select auth.uid()));
  elsif old.status='completed' and new.status<>'completed' then
    new.completed_at:=null; new.completed_by:=null;
  end if;
  if new.status<>'waiting' then new.waiting_reason:=null; new.follow_up_at:=null; end if;
  return new;
end $$;

create or replace function ops_private.log_ticket_insert()
returns trigger language plpgsql security definer set search_path=''
as $$ begin
  insert into public.ops_ticket_events(ticket_id,actor_id,event_type,message)
  values(new.id,new.created_by,'created','Ticket created');
  return new;
end $$;

create or replace function ops_private.log_ticket_change()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if old.status is distinct from new.status then
    insert into public.ops_ticket_events(ticket_id,actor_id,event_type,message,details)
    values(new.id,(select auth.uid()),'status_changed','Status changed from '||old.status||' to '||new.status,jsonb_build_object('from',old.status,'to',new.status));
  end if;
  if old.assigned_to is distinct from new.assigned_to then
    insert into public.ops_ticket_events(ticket_id,actor_id,event_type,message,details)
    values(new.id,(select auth.uid()),'assignment_changed','Ticket assignment changed',jsonb_build_object('from',old.assigned_to,'to',new.assigned_to));
  end if;
  return new;
end $$;

create or replace function ops_private.handle_new_user()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  insert into public.ops_profiles(user_id,email,display_name,role,store_id)
  values(new.id,new.email,coalesce(nullif(new.raw_user_meta_data->>'display_name',''),split_part(coalesce(new.email,'user'),'@',1)),'pending',null)
  on conflict(user_id) do nothing;
  return new;
end $$;

create or replace function ops_private.queue_ticket_created_notification()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  insert into public.ops_notifications(recipient_id,ticket_id,kind,title,body,priority,dedupe_key,data)
  select p.user_id,new.id,'new_ticket',
    case when new.priority='urgent' then 'Urgent new ticket' else 'New store ticket' end,
    s.name||' - '||new.title,
    case when new.priority='urgent' then 'urgent' else 'normal' end,
    'new_ticket:'||new.id::text||':'||p.user_id::text,
    jsonb_build_object('store_id',new.store_id,'ticket_no',new.ticket_no)
  from public.ops_profiles p join public.ops_stores s on s.id=new.store_id
  where p.role in ('admin','hq')
  on conflict(dedupe_key) do nothing;
  return new;
end $$;

create or replace function ops_private.queue_reopen_notification()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  insert into public.ops_ticket_events(ticket_id,actor_id,event_type,message,details)
  values(new.ticket_id,new.requested_by,'reopen_requested','Store requested ticket to be reopened',jsonb_build_object('request_id',new.id,'reason',new.reason));
  insert into public.ops_notifications(recipient_id,ticket_id,kind,title,body,priority,dedupe_key,data)
  select p.user_id,new.ticket_id,'reopen_requested','Store requested reopen',s.name||' - '||t.title,'normal',
    'reopen_requested:'||new.id::text||':'||p.user_id::text,
    jsonb_build_object('request_id',new.id,'reason',new.reason)
  from public.ops_profiles p join public.ops_tickets t on t.id=new.ticket_id join public.ops_stores s on s.id=new.store_id
  where p.role in ('admin','hq')
  on conflict(dedupe_key) do nothing;
  return new;
end $$;

